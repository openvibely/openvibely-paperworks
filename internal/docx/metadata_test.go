package docx

import (
	"crypto/sha256"
	"fmt"
	"github.com/openvibely/openvibely-paperworks/internal/opc"
	"testing"
)

func TestTemplateMetadataPreserved(t *testing.T) {
	for _, spec := range []Spec{{}, {Title: "A <title> & more"}, {Author: "A & B"}, {Title: "Title", Author: "Author"}} {
		raw, err := Build(spec, "")
		if err != nil {
			t.Fatal(err)
		}
		p, err := opc.Read(raw)
		if err != nil {
			t.Fatal(err)
		}
		if spec.Title == "" && spec.Author == "" {
			// Unchanged pinned reference DOCX library blank template and installed Word example.
			if got := fmt.Sprintf("%x", sha256.Sum256(p.Get("docProps/core.xml"))); got != "d14be8284e406d14dc2a576b19f15e7f637b955f9e27a3d9ed871ec99606f7ba" {
				t.Fatalf("reference metadata: %s", got)
			}
		}
		d, err := p.XML("docProps/core.xml")
		if err != nil {
			t.Fatal(err)
		}
		author := spec.Author
		if author == "" {
			author = "python-docx"
		}
		for name, want := range map[string]string{"dc:title": spec.Title, "dc:creator": author, "cp:revision": "1", "dc:description": "generated by python-docx", "dcterms:created": "2013-12-23T23:15:00Z", "dcterms:modified": "2013-12-23T23:15:00Z"} {
			e := d.Root().FindElement(name)
			if e == nil || e.Text() != want {
				t.Fatalf("%s: expected %q", name, want)
			}
		}
	}
}
