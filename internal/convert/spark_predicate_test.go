package convert

import (
	"math"
	"testing"
)

// Expected predicates from unchanged test_document_runtime.py:is_sparkline_mark.
// Acquisition and rendering are deliberately outside this predicate contract.
func TestReferenceSparklineMarkPredicate(t *testing.T) {
	cases := []struct {
		name         string
		stroke, fill []float64
		want         bool
	}{
		{"0-0-0", []float64{}, []float64{0.1511764695882353, 0.35294117647058826, 0.5058823529411764}, true},
		{"0-0-1", []float64{}, []float64{0.1511764705882353, 0.35294117647058826, 0.5058823529411764}, false},
		{"0-0-2", []float64{}, []float64{0.1511764715882353, 0.35294117647058826, 0.5058823529411764}, false},
		{"0-0-3", []float64{}, []float64{0.1411764705882353, 0.36294117547058824, 0.5058823529411764}, true},
		{"0-0-4", []float64{}, []float64{0.1411764705882353, 0.36294117647058827, 0.5058823529411764}, false},
		{"0-0-5", []float64{}, []float64{0.1411764705882353, 0.36294117747058824, 0.5058823529411764}, false},
		{"0-0-6", []float64{}, []float64{0.1411764705882353, 0.35294117647058826, 0.5158823519411765}, true},
		{"0-0-7", []float64{}, []float64{0.1411764705882353, 0.35294117647058826, 0.5158823529411765}, false},
		{"0-0-8", []float64{}, []float64{0.1411764705882353, 0.35294117647058826, 0.5158823539411764}, false},
		{"0-0-9", []float64{}, []float64{}, false},
		{"0-0-10", []float64{}, []float64{0.1411764705882353}, false},
		{"0-0-11", []float64{}, []float64{0.1411764705882353, 0.35294117647058826, 0.5058823529411764, 1.0}, false},
		{"0-1-0", []float64{0.1511764695882353, 0.35294117647058826, 0.5058823529411764}, []float64{}, true},
		{"0-1-1", []float64{0.1511764705882353, 0.35294117647058826, 0.5058823529411764}, []float64{}, false},
		{"0-1-2", []float64{0.1511764715882353, 0.35294117647058826, 0.5058823529411764}, []float64{}, false},
		{"0-1-3", []float64{0.1411764705882353, 0.36294117547058824, 0.5058823529411764}, []float64{}, true},
		{"0-1-4", []float64{0.1411764705882353, 0.36294117647058827, 0.5058823529411764}, []float64{}, false},
		{"0-1-5", []float64{0.1411764705882353, 0.36294117747058824, 0.5058823529411764}, []float64{}, false},
		{"0-1-6", []float64{0.1411764705882353, 0.35294117647058826, 0.5158823519411765}, []float64{}, true},
		{"0-1-7", []float64{0.1411764705882353, 0.35294117647058826, 0.5158823529411765}, []float64{}, false},
		{"0-1-8", []float64{0.1411764705882353, 0.35294117647058826, 0.5158823539411764}, []float64{}, false},
		{"0-1-9", []float64{}, []float64{}, false},
		{"0-1-10", []float64{0.1411764705882353}, []float64{}, false},
		{"0-1-11", []float64{0.1411764705882353, 0.35294117647058826, 0.5058823529411764, 1.0}, []float64{}, false},
		{"1-0-0", []float64{}, []float64{0.8099999990000001, 0.2, 0.2}, true},
		{"1-0-1", []float64{}, []float64{0.81, 0.2, 0.2}, false},
		{"1-0-2", []float64{}, []float64{0.810000001, 0.2, 0.2}, false},
		{"1-0-3", []float64{}, []float64{0.8, 0.20999999900000002, 0.2}, true},
		{"1-0-4", []float64{}, []float64{0.8, 0.21000000000000002, 0.2}, false},
		{"1-0-5", []float64{}, []float64{0.8, 0.21000000100000002, 0.2}, false},
		{"1-0-6", []float64{}, []float64{0.8, 0.2, 0.20999999900000002}, true},
		{"1-0-7", []float64{}, []float64{0.8, 0.2, 0.21000000000000002}, false},
		{"1-0-8", []float64{}, []float64{0.8, 0.2, 0.21000000100000002}, false},
		{"1-0-9", []float64{}, []float64{}, false},
		{"1-0-10", []float64{}, []float64{0.8}, false},
		{"1-0-11", []float64{}, []float64{0.8, 0.2, 0.2, 1.0}, false},
		{"1-1-0", []float64{0.8099999990000001, 0.2, 0.2}, []float64{}, true},
		{"1-1-1", []float64{0.81, 0.2, 0.2}, []float64{}, false},
		{"1-1-2", []float64{0.810000001, 0.2, 0.2}, []float64{}, false},
		{"1-1-3", []float64{0.8, 0.20999999900000002, 0.2}, []float64{}, true},
		{"1-1-4", []float64{0.8, 0.21000000000000002, 0.2}, []float64{}, false},
		{"1-1-5", []float64{0.8, 0.21000000100000002, 0.2}, []float64{}, false},
		{"1-1-6", []float64{0.8, 0.2, 0.20999999900000002}, []float64{}, true},
		{"1-1-7", []float64{0.8, 0.2, 0.21000000000000002}, []float64{}, false},
		{"1-1-8", []float64{0.8, 0.2, 0.21000000100000002}, []float64{}, false},
		{"1-1-9", []float64{}, []float64{}, false},
		{"1-1-10", []float64{0.8}, []float64{}, false},
		{"1-1-11", []float64{0.8, 0.2, 0.2, 1.0}, []float64{}, false},
		{"nan", []float64{}, []float64{math.NaN(), 0.35294117647058826, 0.5058823529411764}, false},
		{"infinity", []float64{}, []float64{math.Inf(1), 0.35294117647058826, 0.5058823529411764}, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			for _, paint := range []bool{false, true} {
				p := referencePDFPath{exactStroke: c.stroke, exactFill: c.fill, stroked: paint, filled: paint}
				if got := referenceIsSparklineMark(p); got != c.want {
					t.Fatalf("predicate=%v want %v", got, c.want)
				}
			}
		})
	}
}
